"""Generate cv/fit_patchcore.ipynb with the repo's cv modules embedded.

The notebook writes cv/patchcore.py and cv/download_mvtec.py verbatim into the
Colab runtime, so Colab and local inference run the exact same code.
Re-run this script whenever those modules change:  python -m cv.build_notebook
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
EMBED = ["__init__.py", "download_mvtec.py", "patchcore.py"]


def md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip().splitlines(keepends=True)}


def code(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.strip().splitlines(keepends=True)}


def build() -> dict:
    cells = [
        md("""
# Fit PatchCore on MVTec AD (bottle, screw)

Generated by `cv/build_notebook.py` — edit the source modules, not this notebook.

**Runtime → Change runtime type → GPU (T4)**, then *Run all*. Output: `patchcore_artifacts.zip`
containing `models/<category>/weights/torch/model.pt` and `reports/raw/{scores.csv, maps_*.npz}`.
Unzip it into the repo root.
"""),
        code("""
!pip install -q anomalib==2.7.0 huggingface_hub
import torch; print("torch", torch.__version__, "| CUDA:", torch.cuda.is_available())
assert torch.cuda.is_available(), "Switch the runtime to GPU"
"""),
    ]
    cells.append(code("import os; os.makedirs('cv', exist_ok=True)"))
    for name in EMBED:
        src = (HERE / name).read_text(encoding="utf-8")
        cells.append(code(f"%%writefile cv/{name}\n{src}"))
    cells += [
        code("""
from pathlib import Path
from cv.download_mvtec import download
DATA, MODELS, RAW = Path("data/mvtec"), Path("models"), Path("reports/raw")
download(DATA)
"""),
        md("Fit one memory bank per category (~ a few minutes each on a T4)."),
        code("""
from cv.patchcore import fit_and_export
for category in ["bottle", "screw"]:
    print(category, "->", fit_and_export(category, DATA, MODELS))
"""),
        md("Score every test image with the exported model — the same code path the local app uses."),
        code("""
from cv.patchcore import score_test_set
csv_path = score_test_set(DATA, MODELS, RAW, device="cuda")
"""),
        md("Sanity check only — the real evaluation (folds, bands, CIs) runs locally in `cv/evaluate.py`."),
        code("""
import pandas as pd
from sklearn.metrics import roc_auc_score
df = pd.read_csv(csv_path)
for cat, g in df.groupby("category"):
    print(f"{cat}: n={len(g)}  image AUROC={roc_auc_score(g.label, g.score):.4f}")
"""),
        code("""
!rm -rf models/_work
!zip -qr patchcore_artifacts.zip models reports/raw
from google.colab import files
files.download("patchcore_artifacts.zip")
"""),
    ]
    return {"cells": cells, "metadata": {"accelerator": "GPU", "colab": {"provenance": []},
                                         "kernelspec": {"name": "python3", "display_name": "Python 3"}},
            "nbformat": 4, "nbformat_minor": 5}


if __name__ == "__main__":
    out = HERE / "fit_patchcore.ipynb"
    out.write_text(json.dumps(build(), indent=1), encoding="utf-8")
    print("wrote", out)
